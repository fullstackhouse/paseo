// ── prototype id ────────────────────────────────────────────────────────
// The page and the committed review comments must agree on this id: prototype.js drops a
// comments.js whose `prototypeId` differs from the page's `data-prototype-id`. This generator
// owns it — it writes comments.js when the file is missing and refuses to run when the
// committed one disagrees, so a rename cannot quietly turn a reviewer's export into
// "no comments yet". Change it here (and rename the directory) in one step.
const PROTOTYPE_ID = 'explorer-auto-open'

const commentsFile = (prototypeId) => `/* Committed prototype review operations.
 *
 * Do not edit this file by hand. Reviewers add comments in the prototype,
 * choose "Export for repository", replace this file, and commit it. Operations
 * are append-only and identified by id; delete operations are tombstones, so
 * merging reviewer exports cannot silently resurrect deleted feedback.
 *
 * \`prototypeId\` must stay equal to PROTOTYPE_ID in generate.mjs.
 */
window.__OM_PROTOTYPE_COMMENTS__ = {
  version: 2,
  prototypeId: '${prototypeId}',
  operations: []
};
`

// The id as the file declares it. Single or double quotes: the scaffold writes the object
// literal above, "Export for repository" writes JSON. Comments are stripped first so a mention
// of the field in the file's header cannot be read as the declaration, and the lookbehind keeps
// a key that merely ends in `prototypeId` from matching.
const ID_IN_COMMENTS = /(?<![\w$])["']?prototypeId["']?\s*:\s*["']([^"']*)["']/

function declaredPrototypeId(source) {
  const code = source.replace(/\/\*[\s\S]*?\*\//g, '').replace(/^\s*\/\/.*$/gm, '')
  const found = ID_IN_COMMENTS.exec(code)
  return found ? found[1] : null
}

function syncComments() {
  const file = path.join(OUT, 'comments.js')
  if (!fs.existsSync(file)) {
    fs.writeFileSync(file, commentsFile(PROTOTYPE_ID))
    console.log('wrote comments.js for', PROTOTYPE_ID)
    return
  }
  const declared = declaredPrototypeId(fs.readFileSync(file, 'utf8'))
  if (declared === null) {
    throw new Error(`comments.js declares no prototypeId. It must read '${PROTOTYPE_ID}' — the id this page is generated with. Fix it, or delete comments.js to have it written afresh (this discards any committed review comments).`)
  }
  if (declared !== PROTOTYPE_ID) {
    throw new Error(`comments.js is for prototype '${declared}', but this page is generated as '${PROTOTYPE_ID}'. The prototype would load and silently ignore its own committed review comments. Set prototypeId in comments.js to '${PROTOTYPE_ID}' (or fix PROTOTYPE_ID here), then re-run.`)
  }
}

