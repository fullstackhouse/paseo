function overview(state) {
  const n = state.next
  const nextCard = n.none
    ? `<div class="px-next px-next-quiet"><span class="px-muted">${esc(n.reason)}</span></div>`
    : `<div class="px-next">
        <div class="px-next-row"><span class="px-btn-primary">${ic(n.icon)} ${esc(n.label)}</span>${state.more?.length ? `<span class="px-btn-ghost">More ${ic('chevron-down')}</span>` : ''}</div>
        <span class="px-next-reason">${esc(n.reason)}</span>
      </div>`

  const a = state.agent
  const pct = Math.round((a.ctx[0] / a.ctx[1]) * 100)
  const agentRows = [
    row('bot', `${esc(a.label)} <span class="px-status px-status-${a.status}">${dot(a.status)} ${statusText(a)}</span>`, esc(a.facts)),
    `<div class="px-row"><span class="px-row-icon"></span><div class="px-row-text"><span class="px-row-meta">Context</span></div><div class="px-meter"><i style="width:${pct}%"></i></div><span class="px-row-meta">${a.ctx[0]}k / ${a.ctx[1] >= 1000 ? a.ctx[1] / 1000 + 'm' : a.ctx[1] + 'k'}</span></div>`,
  ]
  if (state.lineage) agentRows.push(row('lineage', 'Lineage', esc(state.lineage), chev))

  let changes = ''
  if (state.changes === 'error') {
    changes = card('Changes', [row('warn', '<span class="px-danger">Couldn’t read git status</span>', 'fatal: index.lock exists', `<span class="px-btn-outline">${ic('refresh')} Retry</span>`)])
  } else if (state.changes) {
    const c = state.changes
    const sync = [c.ahead ? `↑${c.ahead}` : '', c.behind ? `↓${c.behind}` : ''].filter(Boolean).join(' ') || 'in sync'
    changes = card('Changes', [
      row('branch', esc(state.ws.branch), `→ ${esc(c.upstream)} · ${sync}`),
      row('diff', c.dirty ? `<span class="px-add">+${c.add}</span> <span class="px-del">−${c.del}</span> uncommitted` : 'No uncommitted changes', '', chev),
    ])
  }

  let pr = ''
  if (state.pr === 'error') pr = ''
  else if (state.changes && state.changes !== 'error') {
    if (!state.pr) pr = card('Pull request', [row('pr', '<span class="px-muted">No pull request</span>')])
    else {
      const p = state.pr
      const checks = p.checks.fail ? `<span class="px-danger">${p.checks.fail} failing</span> · ${p.checks.pass} passed` : p.checks.pending ? `${p.checks.pending} running · ${p.checks.pass} passed` : `<span class="px-ok">All ${p.checks.pass} checks passed</span>`
      pr = card('Pull request', [
        row(p.state === 'merged' ? 'merge' : 'pr', `<span class="${p.state === 'merged' ? 'px-merged' : 'px-ok'}">#${p.num}</span> ${esc(p.title)}`, p.state === 'merged' ? 'Merged into main 12m ago' : `${checks} · ${esc(p.review)}`, chev),
      ])
    }
  }

  const plugins = state.asks ? card('Plugins', [row('ask', `${state.asks} asks waiting on you`, 'Asks', chev)]) : ''

  const wsRows = [row('code', 'Open in Zed', '', `<span class="px-chev">${ic('chevron-down')}</span>`)]
  for (const s of state.scripts) wsRows.push(row(s.running ? 'play' : 'terminal', esc(s.name), esc(s.detail), `<span class="px-icon-btn px-icon-sm">${ic(s.running ? 'stop' : 'play')}</span>`))
  wsRows.push(row('monitor', esc(state.ws.host), 'Host'))

  return `<div class="px-overview">
    <div class="px-ov-head"><span class="px-ov-title">${esc(state.ws.title)}</span><span class="px-row-meta">${esc(state.ws.project)}${state.ws.branch ? ' · ' + esc(state.ws.branch) : ''}</span></div>
    ${nextCard}
    ${card('Agent', agentRows)}
    ${plugins}
    ${changes}
    ${pr}
    ${card('Workspace', wsRows)}
  </div>`
}

