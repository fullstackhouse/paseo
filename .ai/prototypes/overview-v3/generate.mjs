// ── renderers ───────────────────────────────────────────────────────────
const CHEV = `<span class="ov-chev">${ic('chevron-right')}</span>`

function identity(st, { menu }) {
  const goal = st.goal ?? st.ws.project
  return `<header class="ov-id">
    <h1 class="ov-title">${esc(st.ws.name)}</h1>
    <span class="ov-kebab ${menu ? 'is-on' : ''}" aria-label="Workspace actions">${ic('more')}</span>
    <p class="ov-goal ${st.goal ? '' : 'is-fallback'}">${esc(goal)}</p>
    ${menu ? `<div class="ov-menu" role="menu">
      <div>${ic('code')} Open in editor</div><div>${ic('copy')} Copy branch name</div><div>${ic('fork')} Lineage</div><hr />
      <div>${ic('archive')} Archive workspace…</div></div>` : ''}
  </header>`
}

function story(st) {
  const s = st.status
  if (!s) return `<p class="ov-quiet">${esc(st.quiet)}</p>`
  return `<section class="ov-story ${s.stale ? 'is-stale' : ''}" role="button" aria-label="Open status">
    <div class="ov-state t-${s.tone}"><i class="ov-dot ${s.live ? 'is-pulse' : ''}"></i>${esc(s.word)}${CHEV}</div>
    ${s.stale ? `<div class="ov-stale">${esc(s.stale)}</div>` : ''}
    <p class="ov-summary">${esc(s.summary)}</p>
    ${s.now ? `<p class="ov-now"><b>Now</b>${esc(s.now)}</p>` : ''}
  </section>`
}

function moveItem(m, lead) {
  const style = lead ? `style="--lead: var(--app-${m.tone === 'merged' ? 'merged' : m.tone === 'muted' ? 'accent' : m.tone})"` : ''
  return `<div class="ov-item ${lead ? 'is-lead' : ''}" ${style}>
    <div class="ov-item-head">
      <span class="ov-item-icon t-${m.tone}">${ic(m.icon)}</span>
      <div class="ov-item-text"><div class="ov-item-title">${esc(m.title)}</div>${m.sub ? `<div class="ov-item-sub">${esc(m.sub)}</div>` : ''}</div>
    </div>
    ${m.actions ? `<div class="ov-actions">${m.actions.map((a) => `<button class="ov-btn ${a.primary ? 'is-primary' : ''} ${a.ghost ? 'is-ghost' : ''}">${esc(a.label)}${a.note ? `<small>${esc(a.note)}</small>` : ''}</button>`).join('')}</div>` : ''}
  </div>`
}

function moves(st) {
  if (!st.moves.length) return `<p class="ov-quiet">${ic('check')} ${esc(st.calm)}</p>`
  const [lead, ...rest] = st.moves
  return `<section class="ov-move">
    <div class="ov-move-label">Your move${st.moves.length > 1 ? `<span class="ov-n">${st.moves.length}</span>` : ''}</div>
    ${moveItem(lead, true)}
    ${rest.map((m) => `<div class="ov-next"><span class="t-${m.tone}">${ic(m.icon)}</span><span>${esc(m.title)}</span>${CHEV}</div>`).join('')}
  </section>`
}

function context(st) {
  if (!st.ctx.length) return ''
  return `<footer class="ov-ctx">${st.ctx.map((c) => `
    <div class="ov-ctx-row"><span class="ov-k">${esc(c.k)}</span><span class="ov-v">${esc(c.v)}</span><span class="ov-w t-${c.tone}">${esc(c.w)}</span>${CHEV}</div>
    ${c.kids ? `<div class="ov-ctx-kids">${c.kids.map((k) => `<div class="ov-ctx-row"><span class="ov-v">${esc(k.v)}</span><span class="ov-w t-${k.tone}">${esc(k.w)}</span></div>`).join('')}</div>` : ''}`).join('')}
  </footer>`
}

function overview(st, opts = {}) {
  return `<div class="ov">${identity(st, opts)}${story(st)}${moves(st)}${context(st)}</div>`
}

// ── frame: the app window at one width ──────────────────────────────────
function frame({ mobile, body }) {
  return `<div class="frame ${mobile ? 'sb-frame-mobile' : 'sb-frame-desktop'}">
    <div class="frame-bar"><div class="frame-dots"><i></i><i></i><i></i></div><span class="frame-url">Paseo</span><span class="sb-frame-label">${mobile ? 'mobile · 390 · sheet' : 'desktop · 1280 · Explorer'}</span></div>
    ${body}
  </div>`
}
