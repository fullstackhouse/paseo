// ── pieces ──────────────────────────────────────────────────────────────
const SHOW = 4
function agentIcon(dot) {
  return `<span class="px-aicon">${ic('agent')}<i class="px-dot px-t-${dot}"></i></span>`
}
function chev() { return `<span class="px-chev">${ic('chevron-right')}</span>` }

function lineageRow(kind, node) {
  return `<div class="px-row px-row-tight">
    <span class="px-lin-icon">${ic(kind)}</span>
    <div class="px-text"><div class="px-title px-1line">${esc(node.name)}</div></div>
    <span class="px-word px-t-${node.tone}">${esc(node.word)}</span>${chev()}
  </div>`
}

function where(st, { menu }) {
  const ws = st.ws
  const sub = ws.folder ? `${ic('folder')} ${esc(ws.project)}` : `${esc(ws.project)} · ${ic('branch')} ${esc(ws.branch)}`
  const kids = st.children.slice(0, SHOW)
  return `<div class="px-where">
    <div class="px-ws">
      <div class="px-text"><div class="px-ws-name">${esc(ws.name)}</div><div class="px-ws-sub">${sub}</div></div>
      <button class="px-iconbtn ${menu ? 'is-on' : ''}" aria-label="Workspace actions">${ic('more')}</button>
      ${menu ? menuPopover() : ''}
    </div>
    <div class="px-row">
      ${agentIcon(st.agent.dot)}
      <div class="px-text"><div class="px-title">${esc(st.agent.title)}</div><div class="px-facts">${esc(st.agent.facts)}</div></div>${chev()}
    </div>
    ${st.parent || kids.length || st.subagents ? `<div class="px-lineage">
      ${st.parent ? `<div class="px-lin-label">From</div>${lineageRow('up', st.parent)}` : ''}
      ${kids.length ? `<div class="px-lin-label">Started ${st.children.length} workspace${st.children.length > 1 ? 's' : ''}</div>${kids.map((n) => lineageRow('down', n)).join('')}` : ''}
      ${st.children.length > SHOW ? `<div class="px-more-link">Show all ${st.children.length}</div>` : ''}
      ${st.subagents ? `<div class="px-lin-foot">${ic('fork')} ${st.subagents} subagent${st.subagents > 1 ? 's' : ''} in this workspace</div>` : ''}
    </div>` : ''}
  </div>`
}

function menuPopover() {
  return `<div class="px-menu" role="menu">
    <div class="px-menu-item">${ic('code')} Open in editor</div>
    <div class="px-menu-item">${ic('copy')} Copy branch name</div>
    <div class="px-menu-item">${ic('fork')} Lineage details</div>
    <div class="px-menu-sep"></div>
    <div class="px-menu-item">${ic('archive')} Archive workspace…</div>
  </div>`
}

function section(title, body, extra = '') {
  return `<section class="px-sec"><div class="px-sec-title">${esc(title)}${extra}</div>${body}</section>`
}

function statusBlock(st) {
  if (!st.status) return section('Status', `<div class="px-quiet">${esc(st.statusFallback)}</div>`)
  const s = st.status
  const tone = s.outdated ? 'muted' : s.tone
  return section('Status', `<div class="px-card px-press">
    <div class="px-card-head">
      <span class="px-badge px-b-${tone}">${esc(s.state)}</span>
      <span class="px-age ${s.outdated ? 'px-outdated' : ''}">${s.outdated ? `outdated · written ${esc(s.age)} ago, PR merged since` : `updated ${esc(s.age)} ago`}</span>
      ${chev()}
    </div>
    <div class="px-summary ${s.outdated ? 'px-dim' : ''}">${esc(s.summary)}</div>
    ${s.now ? `<div class="px-now ${s.outdated ? 'px-dim' : ''}"><b>Now</b> ${esc(s.now)}</div>` : ''}
  </div>`)
}

function movesBlock(st) {
  const count = st.moves.length
  if (!count) return section('Your move', `<div class="px-quiet">${ic('check')} ${esc(st.movesEmpty)}</div>`)
  const rows = st.moves.map((m, i) => `<div class="px-move ${i === 0 ? 'px-move-first' : 'px-press'}">
      <span class="px-micon px-t-${m.tone}">${ic(m.icon)}</span>
      <div class="px-text"><div class="px-title">${esc(m.title)}</div><div class="px-facts">${esc(m.sub)}</div>
        ${i === 0 && m.button ? `<div class="px-move-btn"><button class="px-btn">${esc(m.button)}</button></div>` : ''}
      </div>
      ${i === 0 ? '' : chev()}
    </div>`).join('')
  return section('Your move', `<div class="px-moves">${rows}</div>`, count > 1 ? `<span class="px-count">${count}</span>` : '')
}

function codeBlock(st) {
  if (!st.code) return ''
  const c = st.code
  return section('Code', `<div class="px-row px-press">
      <span class="px-plain">${ic('branch')}</span>
      <div class="px-text"><div class="px-title px-1line t-mono-ish">${esc(c.branch)}</div></div>
      <span class="px-word">${esc(c.sync)} · ${esc(c.diff)}</span>${chev()}
    </div>
    ${c.pr ? `<div class="px-row px-press">
      <span class="px-plain px-t-${c.pr.tone}">${ic(c.pr.tone === 'merged' ? 'merge' : 'pr')}</span>
      <div class="px-text"><div class="px-title px-1line">#${c.pr.num} ${esc(c.pr.title)}</div></div>
      <span class="px-badge px-b-${c.pr.tone}">${esc(c.pr.pill)}</span>${chev()}
    </div>` : ''}`)
}

function moreBlock(st) {
  if (!st.more?.length) return ''
  return section('More', st.more.map((m) => `<div class="px-row px-press"><span class="px-plain">${ic(m.icon)}</span>
    <div class="px-text"><div class="px-title">${esc(m.title)}</div></div><span class="px-word">${esc(m.label)}</span>${chev()}</div>`).join(''))
}

function overview(st, opts = {}) {
  return `<div class="px-ov">${where(st, opts)}${statusBlock(st)}${movesBlock(st)}${codeBlock(st)}${moreBlock(st)}</div>`
}

